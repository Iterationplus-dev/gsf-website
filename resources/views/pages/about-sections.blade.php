<section aria-labelledby="about-strategy">
    <h2 id="about-strategy">Strategic Goals and Objectives</h2>
    <h3>Goals</h3>
    <ul>
        <li>Build a sustainable organisation over the long term by promoting the development of youth co-operatives in Africa.</li>
        <li>Create awareness of the contribution youth co-operatives make to African life.</li>
        <li>Become the reference organisation for youth co-operatives for government, media, academics and business organisations.</li>
        <li>Bring governmental and non-governmental organisations together with young Africans in a lasting and mutually beneficial partnership.</li>
    </ul>
    <h3>Objectives</h3>
    <ul>
        <li>Develop best-practice processes for setting up new youth co-operative businesses.</li>
        <li>Develop support services that co-operatives and individuals recognise as valuable to the success of their own businesses.</li>
        <li>Create awareness of GSF and its activities among communities, relevant government ministries, departments and agencies, and wider society.</li>
        <li>Lift young Africans out of poverty by strengthening their economic activity through effective co-operatives.</li>
        <li>Raise awareness among young Africans of their responsibilities in nation-building.</li>
        <li>Raise the level of economic participation of Africa's female population.</li>
        <li>Create conditions for fuller economic and social inclusion of those affected by past conflict and instability.</li>
    </ul>
</section>

<section aria-labelledby="about-advantage">
    <h2 id="about-advantage">Competitive Advantage of GSFGE</h2>
    <p>GSFGE brings together a focus on youth co-operative businesses, practical experience in co-operative development and a commitment to the economic and social wellbeing of young Africans.</p>
    <p>Its competitive strengths include:</p>
    <ul>
        <li>The knowledge and expertise of its founder, Golden Anikwe, its partners and professional staff in co-operative organisations and management.</li>
        <li>Its commitment to promoting the economic and social wellbeing of Africa's young people.</li>
    </ul>
    <h3>The founder</h3>
    <p>Golden Anikwe brings international experience as a co-operative practitioner. He founded Co-operative Support Services Limited in Ireland, which promoted co-operatives among ethnic minority communities, trained their members and staff, and guided their operations.</p>
    <h3>His connections</h3>
    <p>Co-operative Support Services in Ireland was for a period a member of the International Co-operative Alliance, the international umbrella organisation for co-operatives. This background informs GSFGE's approach to co-operative development and partnership.</p>
    <h3>Filling a gap</h3>
    <p>GSFGE was established to respond to young Africans' need for practical support in forming and running co-operative businesses. It draws on the co-operative model as a route to sustainable employment, increased household wealth and fuller participation in economic life.</p>
</section>
